def art_path(art):
    rows = [r for r in art.strip("\n").split("\n")]
    d = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] in "#~":
                x0 = x
                while x < len(row) and row[x] == row[x0]:
                    x += 1
                d.append(f"M{x0} {y}h{x - x0}v1h-{x - x0}z")
            else:
                x += 1
    return "".join(d)


def fetch(name):
    os.makedirs(SRC, exist_ok=True)
    path = os.path.join(SRC, name + ".svg")
    if not os.path.exists(path):
        with urllib.request.urlopen(CDN.format(name), timeout=30) as r:
            open(path, "wb").write(r.read())
    return open(path).read()


def main():
    symbols, missing = [], []
    for sid, art in ART.items():
        symbols.append(f'<symbol id="{sid}" viewBox="0 0 16 16"><path d="{art_path(art)}"/></symbol>')
    for sid, name in ICONS.items():
        try:
            svg = fetch(name)
        except Exception:
            missing.append(sid)
            continue
        body = re.sub(r"^.*?<svg[^>]*>|</svg>\s*$", "", svg, flags=re.S).strip()
        symbols.append(f'<symbol id="{sid}" viewBox="0 0 24 24">{body}</symbol>')
    sprite = ('<svg xmlns="http://www.w3.org/2000/svg" fill="currentColor" shape-rendering="crispEdges">\n'
              '<!-- UI icons: pixelarticons, MIT License, https://pixelarticons.com; power icons drawn for this map -->\n'
              + "\n".join(symbols) + "\n</svg>\n")
    open(OUT, "w").write(sprite)
    print(f"{len(symbols)} icons -> {OUT}; missing: {missing or 'none'}")


if __name__ == "__main__":
    main()
